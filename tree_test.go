// npmLockFixture: the project requires express and next. express 4.18.2 needs
// path-to-regexp 0.1.7 (a nested copy lives under express), next needs semver
// through postcss, and semver also sits at the top level for the project.
const npmLockFixture = `{
  "name": "app",
  "lockfileVersion": 3,
  "packages": {
    "": {
      "name": "app",
      "dependencies": { "express": "^4.18.2", "next": "^14.1.0" },
      "devDependencies": { "semver": "^7.5.1" }
    },
    "node_modules/express": {
      "version": "4.18.2",
      "dependencies": { "path-to-regexp": "0.1.7", "qs": "6.11.0" }
    },
    "node_modules/express/node_modules/path-to-regexp": { "version": "0.1.7" },
    "node_modules/qs": { "version": "6.11.0" },
    "node_modules/next": {
      "version": "14.1.0",
      "dependencies": { "postcss": "8.4.31" },
      "peerDependencies": { "react": ">=18" }
    },
    "node_modules/postcss": {
      "version": "8.4.31",
      "dependencies": { "nanoid": "^3.3.6", "semver": "^7.0.0" }
    },
    "node_modules/nanoid": { "version": "3.3.7" },
    "node_modules/semver": { "version": "7.5.1", "dev": true },
    "node_modules/linked": { "resolved": "packages/linked", "link": true },
    "packages/linked": { "version": "1.0.0", "dependencies": { "qs": "^6.0.0" } }
  }
}`

func TestParseTreeNpmLock(t *testing.T) {
	tr, err := ParseTree("web/package-lock.json", npmLockFixture)
	if err != nil {
		t.Fatal(err)
	}
	if got := tr.Versions("path-to-regexp"); !reflect.DeepEqual(got, []string{"0.1.7"}) {
		t.Fatalf("versions = %v", got)
	}
	if v, ok := tr.RootRequires("express"); !ok || v != "4.18.2" {
		t.Fatalf("root requires express = %q %v", v, ok)
	}
	// The workspace member stands in for the project, so qs is also required by the root.
	if _, ok := tr.RootRequires("qs"); !ok {
		t.Fatal("a workspace member's requirement should be a root requirement")
	}
	if _, ok := tr.RootRequires("path-to-regexp"); ok {
		t.Fatal("path-to-regexp is not required by the project")
	}

	parents := tr.Parents("path-to-regexp", "0.1.7")
	if len(parents) != 1 || parents[0].Name != "express" || parents[0].Range != "0.1.7" || parents[0].Root {
		t.Fatalf("parents = %+v", parents)
	}

	// semver is required by the project (dev) and by postcss.
	sp := tr.Parents("semver", "7.5.1")
	if len(sp) != 2 || !sp[0].Root || sp[1].Name != "postcss" || sp[1].Range != "^7.0.0" {
		t.Fatalf("semver parents = %+v", sp)
	}

	path := tr.PathTo("nanoid", "3.3.7")
	want := []string{"next 14.1.0", "postcss 8.4.31", "nanoid 3.3.7"}
	if !reflect.DeepEqual(path.Steps, want) {
		t.Fatalf("path = %v", path.Steps)
	}
	if !reflect.DeepEqual(path.Names, []string{"next", "postcss", "nanoid"}) {
		t.Fatalf("names = %v", path.Names)
	}
	if p := tr.PathTo("nanoid", "9.9.9"); len(p.Steps) != 0 {
		t.Fatalf("unknown version has a path: %v", p.Steps)
	}

	anc := tr.DirectAncestors("nanoid", "3.3.7")
	if len(anc) != 1 || anc[0].Name != "next" || anc[0].Version != "14.1.0" {
		t.Fatalf("ancestors = %+v", anc)
	}
	// A package the project requires itself is its own nearest ancestor.
	anc = tr.DirectAncestors("semver", "7.5.1")
	if len(anc) == 0 || anc[0].Name != "semver" {
		t.Fatalf("ancestors of a direct package = %+v", anc)
	}
}

func TestParseTreeNpmLockNestedResolution(t *testing.T) {
	lock := `{"lockfileVersion":2,"packages":{
      "":{"dependencies":{"a":"1"}},
      "node_modules/a":{"version":"1.0.0","dependencies":{"b":"^1"}},
      "node_modules/a/node_modules/b":{"version":"1.2.0","dependencies":{"c":"^2"}},
      "node_modules/a/node_modules/b/node_modules/c":{"version":"2.0.0"},
      "node_modules/c":{"version":"1.0.0"}
    }}`
	tr, err := ParseTree("package-lock.json", lock)
	if err != nil {
		t.Fatal(err)
	}
	// b needs c, and b's own node_modules holds c 2.0.0, not the top level 1.0.0.
	p := tr.Parents("c", "2.0.0")
	if len(p) != 1 || p[0].Name != "b" {
		t.Fatalf("parents of c 2.0.0 = %+v", p)
	}
	if got := tr.Parents("c", "1.0.0"); len(got) != 0 {
		t.Fatalf("top level c has requirers %+v", got)
	}
	if got := tr.Versions("c"); len(got) != 2 {
		t.Fatalf("versions of c = %v", got)
	}
}

func TestParseTreeNpmLockErrors(t *testing.T) {
	if _, err := ParseTree("package-lock.json", `{"lockfileVersion":1,"dependencies":{"a":{"version":"1.0.0"}}}`); !errors.Is(err, ErrNoTree) {
		t.Fatalf("v1 lock: %v", err)
	}
	if _, err := ParseTree("package-lock.json", `{`); err == nil || errors.Is(err, ErrNoTree) {
		t.Fatalf("broken JSON should be a parse error, got %v", err)
	}
	if _, err := ParseTree("go.sum", ""); !errors.Is(err, ErrNoTree) {
		t.Fatalf("go.sum: %v", err)
	}
}

const cargoLockFixture = `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "hyper",
 "serde 1.0.150",
]

[[package]]
name = "hyper"
version = "0.14.20"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "bytes",
 "serde 1.0.200 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "bytes"
version = "1.2.1"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "serde"
version = "1.0.150"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "serde"
version = "1.0.200"
source = "registry+https://github.com/rust-lang/crates.io-index"

[metadata]
"checksum bytes 1.2.1" = "abc"
`

func TestParseTreeCargoLock(t *testing.T) {
	tr, err := ParseTree("Cargo.lock", cargoLockFixture)
	if err != nil {
		t.Fatal(err)
	}
	if got := tr.Versions("serde"); !reflect.DeepEqual(got, []string{"1.0.150", "1.0.200"}) {
		t.Fatalf("serde versions = %v", got)
	}
	// The member crate "app" is the project: hyper and serde 1.0.150 are root requirements.
	if v, ok := tr.RootRequires("hyper"); !ok || v != "0.14.20" {
		t.Fatalf("root requires hyper = %q %v", v, ok)
	}
	if _, ok := tr.RootRequires("bytes"); ok {
		t.Fatal("bytes is transitive")
	}
	p := tr.Parents("bytes", "1.2.1")
	if len(p) != 1 || p[0].Name != "hyper" || p[0].Range != "" {
		t.Fatalf("bytes parents = %+v", p)
	}
	if path := tr.PathTo("bytes", "1.2.1"); !reflect.DeepEqual(path.Steps, []string{"hyper 0.14.20", "bytes 1.2.1"}) {
		t.Fatalf("path = %v", path.Steps)
	}
	// serde 1.0.200 comes only through hyper.
	if a := tr.DirectAncestors("serde", "1.0.200"); len(a) != 1 || a[0].Name != "hyper" {
		t.Fatalf("serde ancestors = %+v", a)
	}
	// Local crates are not nodes.
	if len(tr.Versions("app")) != 0 {
		t.Fatal("the member crate must not be a package")
	}
}

